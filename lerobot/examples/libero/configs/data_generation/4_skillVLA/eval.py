def build_html(
    summary: str,
    levels: list[int],
    counts: list[int],
    entry_data: list[dict | None],
    samples: list[list[dict]],
    dim_labels: list[str],
) -> str:
    return (
        HTML.replace("__SUMMARY__", summary)
        .replace("__LEVELS__", json.dumps(levels))
        .replace("__COUNTS__", json.dumps(counts))
        .replace("__ENTRY_DATA__", json.dumps(entry_data))
        .replace("__SAMPLES__", json.dumps(samples))
        .replace("__DIM_LABELS__", json.dumps(dim_labels))
    )


def main() -> None:
    args = parse_args()
    random.seed(args.seed)
    np.random.seed(args.seed)

    paths = resolve_paths(args)
    for key in ("raw_dataset", "skills_dir", "dino_tokens", "model", "latents"):
        if not paths[key].exists():
            raise FileNotFoundError(f"{key} not found: {paths[key]}")

    print("SkillVLA FSQ eval")
    for k, v in paths.items():
        print(f"  {k:12s}: {v}")

    device = choose_device(args.device)
    model, cfg = load_model(str(paths["model"]), device)
    end_threshold = cfg.end_threshold if args.end_threshold is None else args.end_threshold
    codebook_size = codebook_size_from_model(model)
    levels = fsq_levels_from_model(model)

    segments, dec_states, dec_targets, metadata = load_skill_files(
        paths["skills_dir"],
        eef_dims=args.eef_dims,
        gripper_action_dim=args.gripper_action_dim,
        zero_start_eef=args.zero_start_eef,
    )
    action_dim = int(dec_targets[0].shape[-1])
    dim_labels = [f"d{i}" for i in range(action_dim - 1)] + ["grip"]
    n_patches = model.n_patches

    lat = np.load(paths["latents"])
    latents = lat["latents"].astype(np.float32)
    tokens = lat["tokens"].astype(np.int32)
    if len(tokens) != len(metadata):
        raise ValueError(f"Latents skill count {len(tokens)} != skillset count {len(metadata)}")

    all_indices = list(range(len(metadata)))
    if args.max_eval_skills > 0 and args.max_eval_skills < len(all_indices):
        eval_indices = sorted(random.sample(all_indices, args.max_eval_skills))
    else:
        eval_indices = all_indices

    dec_tokens = load_dino_tokens_eval(paths["dino_tokens"], metadata, eval_indices)
    if getattr(cfg, "decoder_image_mode", "dino_only") == "dino_flags" and paths["patch_flags"].exists():
        patch_flags = load_patch_flags(paths["patch_flags"], metadata, n_patches=n_patches)
    else:
        patch_flags = [np.zeros((m["length"], n_patches, 2), dtype=np.float32) for m in metadata]

    by_entry_eval: dict[int, list[int]] = defaultdict(list)
    for i in eval_indices:
        by_entry_eval[int(tokens[i])].append(i)
    sample_indices_by_entry = {}
    for tok, idxs in by_entry_eval.items():
        n = min(args.samples_per_entry, len(idxs))
        sample_indices_by_entry[tok] = sorted(random.sample(idxs, n)) if n > 0 else []
    sample_indices = {i for idxs in sample_indices_by_entry.values() for i in idxs}

    per_skill: dict[int, dict] = {}
    sample_cache: dict[int, dict] = {}
    print(f"[eval] Running decoder on {len(eval_indices)}/{len(metadata)} skills with device={device}")
    for i in tqdm(eval_indices, desc="Decoding skills"):
        T = int(metadata[i]["length"])
        pred_d, pred_p = run_decode_single(
            model,
            latents[i],
            dec_states[i][:T],
            dec_tokens[i][:T],
            patch_flags[i][:T],
            device,
        )
        pred_d0 = pred_d[:T, 0, :] if pred_d.ndim == 3 else pred_d[:T]
        pred_p = pred_p[:T]
        metrics = compute_skill_metrics(pred_d[:T], dec_targets[i][:T], pred_p, end_threshold)
        per_skill[i] = metrics
        if i in sample_indices:
            sample_cache[i] = {
                "plot": make_error_plot(dec_targets[i][:T], pred_d0, pred_p, end_threshold, dim_labels),
            }

    counts, entry_data = aggregate_entry_data(per_skill, tokens, codebook_size)

    sample_meta = collect_sample_images(
        paths["raw_dataset"],
        args.image_key,
        metadata,
        sample_indices_by_entry,
        args.thumb_size,
    )

    samples: list[list[dict]] = [[] for _ in range(codebook_size)]
    for tok, rows in sample_meta.items():
        merged = []
        for row in rows:
            row = dict(row)
            row["plot"] = sample_cache[row["idx"]]["plot"]
            merged.append(row)
        samples[tok] = merged

    mse_vals = [m["mse_all"] for m in per_skill.values()]
    len_vals = [m["timing_abs"] for m in per_skill.values()]
    summary = (
        f"data={args.data} | run={paths['skillvla_dir'].name} | "
        f"eval={len(eval_indices)}/{len(metadata)} skills | entries used={sum(c > 0 for c in counts)}/{codebook_size} | "
        f"delta MSE mean={np.mean(mse_vals):.4g} | length/end |err| mean={np.mean(len_vals):.2f} steps | "
        f"decoder_mode={cfg.decoder_output_mode} | image_mode={getattr(cfg, 'decoder_image_mode', 'unknown')} | "
        f"levels={'x'.join(map(str, levels))}"
    )

    html = build_html(summary, levels, counts, entry_data, samples, dim_labels)
    paths["output_html"].parent.mkdir(parents=True, exist_ok=True)
    paths["output_html"].write_text(html, encoding="utf-8")
    print(f"[eval] HTML saved -> {paths['output_html']}")


if __name__ == "__main__":
    main()
