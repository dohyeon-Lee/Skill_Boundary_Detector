def resolve_paths(args: argparse.Namespace) -> dict[str, Path]:
    cfg = load_config(args.data)
    root = Path(args.dataset_root)
    data_dir = root / f"{args.data}_data"
    for_fsq = data_dir / f"{args.data}_for_FSQ"
    skillvla_root = data_dir / f"{args.data}_for_skillVLA"

    if args.skillvla_dir:
        skillvla_dir = Path(args.skillvla_dir)
    elif args.run_name:
        skillvla_dir = skillvla_root / args.run_name
    else:
        skillvla_dir = skillvla_root / cfg.fsq_run

    paths = {
        "raw_dataset": root / args.data,
        "skills_dir": for_fsq / f"{args.data}_skillset" / "skills",
        "dino_tokens": for_fsq / f"{args.dino_tag}_tokens.npz",
        "patch_flags": for_fsq / "patch_flags.npz",
        "skillvla_dir": skillvla_dir,
        "model": skillvla_dir / "FSQ.pt",
        "latents": skillvla_dir / "skill_latents.npz",
    }
    if args.output_html:
        paths["output_html"] = Path(args.output_html)
    else:
        script_dir = Path(__file__).resolve().parent
        paths["output_html"] = script_dir / "html" / f"{args.data}_{skillvla_dir.name}_eval.html"
    return paths


def choose_device(name: str) -> str:
    if name == "auto":
        return "cuda" if torch.cuda.is_available() else "cpu"
    if name == "cuda" and not torch.cuda.is_available():
        print("[eval] CUDA requested but unavailable; using CPU.")
        return "cpu"
    return name


def load_dino_tokens_eval(
    features_path: Path,
    metadata: list[dict],
    eval_indices: list[int],
) -> list:
    """Load DINO tokens only for eval_indices using memory-mapping to avoid loading 27 GB into RAM."""
    print(f"[eval] Loading DINO tokens (mmap) for {len(eval_indices)}/{len(metadata)} skills ...")
    d = np.load(str(features_path), allow_pickle=False, mmap_mode="r")
    features = d["features"]  # mmap: not read into RAM yet
    offsets = d["offsets"].astype(np.int64)

    if features.ndim == 2:
        features = features[:, None, :]

    if len(offsets) != len(metadata) + 1:
        raise ValueError(f"Offset count {len(offsets) - 1} != skill count {len(metadata)}")

    clips: list = [None] * len(metadata)
    for i in eval_indices:
        m = metadata[i]
        expected = (int(m["episode_id"]), int(m["frame_start"]), int(m["frame_end"]), int(m["length"]))
        got = (int(d["episode_id"][i]), int(d["frame_start"][i]), int(d["frame_end"][i]), int(d["length"][i]))
        if got != expected:
            raise ValueError(f"DINO metadata mismatch at index {i}: got {got}, expected {expected}")
        clips[i] = features[offsets[i] : offsets[i + 1]].astype(np.float32)

    print(f"[eval] DINO tokens ready — clip shape example: {clips[eval_indices[0]].shape}")
    return clips


def codebook_size_from_model(model) -> int:
    return int(model.fsq.codebook_size)


def fsq_levels_from_model(model) -> list[int]:
    levels = getattr(model.fsq, "levels", None)
    if levels is None:
        levels = getattr(model.fsq, "_levels", None)
    if levels is None:
        size = codebook_size_from_model(model)
        side = round(size ** (1.0 / 3.0))
        return [side, side, side] if side**3 == size else [size, 1, 1]
    if isinstance(levels, torch.Tensor):
        return [int(x) for x in levels.detach().cpu().tolist()]
    return [int(x) for x in levels]


def make_error_plot(
    gt: np.ndarray,
    pred: np.ndarray,
    end_prob: np.ndarray,
    threshold: float,
    dim_labels: list[str],
) -> str:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    t = np.arange(len(gt))
    dim_count = gt.shape[-1]
    fig, axes = plt.subplots(dim_count + 1, 1, figsize=(4.0, 1.05 * (dim_count + 1)), squeeze=False)
    for d, ax in enumerate(axes[:dim_count, 0]):
        label = dim_labels[d] if d < len(dim_labels) else f"d{d}"
        ax.plot(t, gt[:, d], color="#1976D2", linewidth=0.9, label="GT")
        ax.plot(t, pred[:, d], color="#D32F2F", linewidth=0.9, linestyle="--", label="Pred")
        ax.set_ylabel(label, fontsize=7, rotation=0, labelpad=20)
        ax.tick_params(labelsize=6)
        ax.yaxis.set_major_locator(plt.MaxNLocator(3))
        ax.set_xticks([])

    ax = axes[dim_count, 0]
    if end_prob.ndim == 2:
        end_show = end_prob.max(axis=1)
    else:
        end_show = end_prob
    end_gt = np.zeros(len(gt), dtype=np.float32)
    end_gt[-1] = 1.0
    ax.plot(t, end_gt, color="#1976D2", linewidth=0.9, label="GT end")
    ax.plot(t, end_show, color="#7B1FA2", linewidth=0.9, linestyle="--", label="Pred end")
    ax.axhline(threshold, color="#999", linewidth=0.7, linestyle=":")
    ax.set_ylabel("end", fontsize=7, rotation=0, labelpad=20)
    ax.set_ylim(-0.05, 1.05)
    ax.tick_params(labelsize=6)
    axes[0, 0].legend(fontsize=6, loc="upper right", framealpha=0.6)
    axes[-1, 0].set_xlabel("t", fontsize=7)
    fig.tight_layout(h_pad=0.25)
    buf = io.BytesIO()
    fig.savefig(buf, format="jpeg", dpi=82, bbox_inches="tight", pil_kwargs={"quality": 72})
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode()


def collect_sample_images(
    raw_dataset: Path,
    image_key: str,
    metadata: list[dict],
    sample_indices_by_entry: dict[int, list[int]],
    thumb_size: int,
) -> dict[int, list[dict]]:
    episodes_meta = _load_episodes_meta(raw_dataset)
    image_key = _resolve_image_key(episodes_meta, image_key)
    all_indices = sorted({i for idxs in sample_indices_by_entry.values() for i in idxs})
    ep_to_indices: dict[int, list[int]] = defaultdict(list)
    for i in all_indices:
        ep_to_indices[int(metadata[i]["episode_id"])].append(i)

    blank = _img_to_b64(np.full((thumb_size, thumb_size, 3), 80, np.uint8), thumb_size)
    pair_by_idx: dict[int, tuple[str, str]] = {}

    for ep_id, indices in tqdm(sorted(ep_to_indices.items()), desc="Extracting sample thumbnails"):
        try:
            row = _episode_row(episodes_meta, ep_id)
            from_ts = float(row[f"videos/{image_key}/from_timestamp"])
            to_ts = float(row[f"videos/{image_key}/to_timestamp"])
            expected_len = int(row["length"])
            clip = _read_episode_clip(_video_path(raw_dataset, episodes_meta, ep_id, image_key), from_ts, to_ts, expected_len)
            for i in indices:
                m = metadata[i]
                start = _clip_frame_or_blank(clip, int(m["frame_start"]), thumb_size)
                end = _clip_frame_or_blank(clip, max(0, int(m["frame_end"]) - 1), thumb_size)
                pair_by_idx[i] = (_img_to_b64(start, thumb_size), _img_to_b64(end, thumb_size))
        except Exception as exc:
            print(f"[eval] thumbnail warning ep{ep_id}: {exc}")
            for i in indices:
                pair_by_idx[i] = (blank, blank)

    out: dict[int, list[dict]] = {}
    for tok, indices in sample_indices_by_entry.items():
        out[tok] = []
        for i in indices:
            s_b64, e_b64 = pair_by_idx.get(i, (blank, blank))
            m = metadata[i]
            out[tok].append(
                {
                    "idx": int(i),
                    "ep": int(m["episode_id"]),
                    "sk": int(m["skill_index"]),
                    "fs": int(m["frame_start"]),
                    "fe": int(m["frame_end"]),
                    "start": s_b64,
                    "end": e_b64,
                }
            )
    return out


def aggregate_entry_data(per_skill: dict[int, dict], tokens: np.ndarray, codebook_size: int) -> tuple[list[int], list[dict | None]]:
    counts = [0] * codebook_size
    by_entry: dict[int, list[dict]] = defaultdict(list)
    for i, tok in enumerate(tokens):
        tok = int(tok)
        counts[tok] += 1
        if i in per_skill:
            by_entry[tok].append(per_skill[i])

    entry_data: list[dict | None] = []
    for tok in range(codebook_size):
        ms = by_entry.get(tok, [])
        if not ms:
            entry_data.append(None)
            continue
        entry_data.append(
            {
                "n_eval": len(ms),
                "mse_all": float(np.mean([m["mse_all"] for m in ms])),
                "mse_per_dim": [
                    float(np.mean([m["mse_per_dim"][d] for m in ms]))
                    for d in range(len(ms[0]["mse_per_dim"]))
                ],
                "mse_eef": float(np.mean([m["mse_eef"] for m in ms])),
                "mse_grip": float(np.mean([m["mse_grip"] for m in ms])),
                "length_abs": float(np.mean([m["timing_abs"] for m in ms])),
                "length_signed": float(np.mean([m["timing_err"] for m in ms])),
                "end_bce": float(np.mean([m["end_bce"] for m in ms])),
                "end_acc": float(np.mean([m["end_acc"] for m in ms])),
                "mean_len": float(np.mean([m["length"] for m in ms])),
            }
        )
    return counts, entry_data


